#[derive(Debug)]
pub enum Error {
    /// A file that has to be there is not.
    Missing(String),
    /// A file is there and is not what it claims to be.
    Malformed(String),
    /// Well formed, and this build cannot represent it.
    Unsupported(String),
    Core(String),
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Error::Missing(m) => write!(f, "{m}"),
            Error::Malformed(m) => write!(f, "malformed: {m}"),
            Error::Unsupported(m) => write!(f, "unsupported: {m}"),
            Error::Core(m) => write!(f, "{m}"),
        }
    }
}
impl std::error::Error for Error {}

pub type Res<T> = Result<T, Error>;

