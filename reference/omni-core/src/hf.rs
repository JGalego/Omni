//! Hugging Face model directory import — the whole repo, not just the weights.
//!
//! `docs/design/import-export.md` §3 lists "Hugging Face repo" as its own row,
//! and the reason it is a row rather than a footnote on safetensors is that a
//! model on the hub is five files that only mean something together:
//!
//! | file | what it carries | where it lands |
//! |---|---|---|
//! | `model*.safetensors` / `pytorch_model*.bin` | the weights | §04 tensors |
//! | `config.json` | architecture parameters | §06.2 `arch` |
//! | `tokenizer.json` | the tokenizer | §06.7 `omni.tok/tokenizer` |
//! | `tokenizer_config.json` | the chat template | §06.9 OMNI-CT |
//! | `generation_config.json` | decoding defaults | §06.6 |
//!
//! Importing them one at a time produces five containers that do not know about
//! each other. Importing them together produces the thing OMNI is for: one
//! content-addressed artifact where the tokenizer that was shipped with these
//! weights is *in* the file, addressed by digest, rather than being a second
//! download that might not match.
//!
//! ## What this importer will not do
//!
//! It will not invent. `config.json` has no license field, so no license is
//! written. HF's config does not state RoPE's pairing convention — the
//! `interleaved` flag of §06.3, which the specification calls out as the field
//! that "has caused more silent output corruption in format conversions than
//! any other" — so it is written only for the model families where the
//! `transformers` implementation is unambiguous, and named as an assumption
//! when it is.
//!
//! It will not claim a tokenizer it cannot run. Every normalizer, pre-tokenizer
//! and decoder step outside §06.7's catalogue is imported as `unsupported` with
//! its own name, so `omni verify --tokenizer` reports *indeterminate* rather
//! than producing ids that are wrong in a way nobody notices.
//!
//! And it produces **no conformance vectors** (§06.7.1). Vectors have to come
//! from the source tokenizer, and this importer cannot run `tokenizers`; a
//! vector generated by the encoder it is supposed to test cannot fail. The
//! absence is recorded in the fidelity report rather than papered over.

