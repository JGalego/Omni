    #[test]
    fn sharded_weights_land_in_one_model_in_the_order_they_were_given() {
        let mut f = files();
        f.shards = vec![
            Shard {
                name: "model-00001-of-00002.safetensors".into(),
                kind: Weights::Safetensors,
                bytes: safetensors_shard(&["model.embed_tokens.weight"]),
            },
            Shard {
                name: "model-00002-of-00002.safetensors".into(),
                kind: Weights::Safetensors,
                bytes: safetensors_shard(&["lm_head.weight"]),
            },
        ];
        let out = import(&f, &ImportOpts::default()).expect("imports");
        assert_eq!(out.report.verified_tensors, 2);
        // The source digest covers both shards *and* their names, so two repos
        // whose shards differ only in how they were cut do not collide.
        let mut g = f;
        g.shards.swap(0, 1);
        let other = import(&g, &ImportOpts::default()).expect("imports");
        assert_ne!(out.report.source_digest, other.report.source_digest);
    }

