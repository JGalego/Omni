/// `config.json` keys with a §06.2 spelling. Everything else is kept under
/// `hf`, so nothing is lost and nothing is ambiguous about which name it had.
const CONFIG_MAP: &[(&str, &str)] = &[
    ("hidden_size", "hidden_size"),
    ("num_hidden_layers", "n_layers"),
    ("num_attention_heads", "n_heads"),
    ("num_key_value_heads", "n_kv_heads"),
    ("head_dim", "head_dim"),
    ("intermediate_size", "ffn_hidden"),
    ("hidden_act", "activation"),
    ("max_position_embeddings", "n_ctx"),
    ("vocab_size", "vocab_size"),
];

/// Model families whose `transformers` implementation rotates RoPE in
/// NeoX pairing — halves, not adjacent pairs. §06.3 requires `interleaved`
/// when `kind` is `rope`, and this is the only honest way to supply it: from
/// knowledge of the implementation, recorded as an assumption, for families
/// where there is no ambiguity. An unlisted family gets no `rope` block at all.
const NEOX_PAIRING: &[&str] = &[
    "llama",
    "mistral",
    "mixtral",
    "qwen2",
    "qwen3",
    "gemma",
    "gemma2",
    "phi3",
    "olmo",
    "starcoder2",
    "cohere",
    "granite",
];

fn jnum(v: &json::Value) -> Option<Value> {
    Some(match v {
        json::Value::U(u) => Value::U(*u),
        json::Value::I(i) => Value::I(*i),
        json::Value::F(f) => Value::F64(*f),
        _ => return None,
    })
}

fn to_cbor(v: &json::Value) -> Value {
    match v {
        json::Value::Null => Value::Null,
        json::Value::Bool(b) => Value::Bool(*b),
        json::Value::Str(s) => Value::text(s.clone()),
        json::Value::Array(a) => Value::Array(a.iter().map(to_cbor).collect()),
        json::Value::Object(m) => {
            Value::map(m.iter().map(|(k, x)| (k.as_str(), to_cbor(x))).collect())
        }
        other => jnum(other).unwrap_or(Value::Null),
    }
}

/// Reads `config.json` into a §06.2 architecture descriptor.
pub fn arch_of(cfg: &json::Value, notes: &mut Vec<Note>) -> (String, Vec<(String, Value)>) {
    let family = cfg
        .get("model_type")
        .and_then(|x| x.as_str())
        .unwrap_or("unknown")
        .to_string();
    let mut params: Vec<(String, Value)> = Vec::new();
    let mut mapped = std::collections::BTreeSet::new();
    for (hf, omni) in CONFIG_MAP {
        if let Some(v) = cfg.get(hf) {
            if let Some(c) = jnum(v).or_else(|| v.as_str().map(Value::text)) {
                params.push(((*omni).to_string(), c));
                mapped.insert(hf.to_string());
            }
        }
    }

    // §06.2's `norm` block, which HF spreads across two differently named keys
    // depending on the family.
    let eps = cfg
        .get("rms_norm_eps")
        .or_else(|| cfg.get("layer_norm_eps"))
        .or_else(|| cfg.get("layer_norm_epsilon"));
    if let Some(e) = eps.and_then(jnum) {
        let rms = cfg.get("rms_norm_eps").is_some();
        params.push((
            "norm".into(),
            Value::map(vec![
                (
                    "kind",
                    Value::text(if rms { "rmsnorm" } else { "layernorm" }),
                ),
                ("eps", e),
                // Every family in `transformers` that states one of these keys
                // normalizes before the sublayer.
                ("pre", Value::Bool(true)),
            ]),
        ));
        for k in ["rms_norm_eps", "layer_norm_eps", "layer_norm_epsilon"] {
            mapped.insert(k.to_string());
        }
    }

    // §06.3. `theta` is stated; `interleaved` never is.
    if let Some(theta) = cfg.get("rope_theta").and_then(jnum) {
        mapped.insert("rope_theta".into());
        if NEOX_PAIRING.contains(&family.as_str()) {
            let mut rope = vec![
                ("kind", Value::text("rope")),
                ("theta", theta),
                ("interleaved", Value::Bool(false)),
            ];
            if let Some(scaling) = cfg.get("rope_scaling") {
                mapped.insert("rope_scaling".into());
                if !matches!(scaling, json::Value::Null) {
                    rope.push(("scaling", to_cbor(scaling)));
                }
            }
            params.push(("rope".into(), Value::map(rope)));
            notes.push(Note {
                item: "rope.interleaved".into(),
                reason: "config.json never states RoPE's pairing convention, and §06.3 \
                         calls it the field that has caused the most silent corruption"
                    .into(),
                action: format!(
                    "written as `false` (NeoX halves) from the `transformers` \
                     implementation of `{family}`, not from the file"
                ),
            });
        } else {
            notes.push(Note {
                item: "rope".into(),
                reason: format!(
                    "`{family}` is not a family whose RoPE pairing this build knows, and \
                     §06.3 requires `interleaved` when `kind` is `rope`"
                ),
                action: "no rope block written; `rope_theta` is kept under `hf`".into(),
            });
            mapped.remove("rope_theta");
        }
    }

    if let Some(json::Value::Bool(t)) = cfg.get("tie_word_embeddings") {
        params.push(("tie_embeddings".into(), Value::Bool(*t)));
        mapped.insert("tie_word_embeddings".into());
    }

    // Everything else, verbatim, under its own name. `arch.params` is
    // explicitly free-form (§06.2), so keeping the file's own keys costs
    // nothing and loses nothing.
    if let json::Value::Object(m) = cfg {
        let rest: Vec<(&str, Value)> = m
            .iter()
            .filter(|(k, _)| !mapped.contains(*k) && *k != "model_type")
            .map(|(k, v)| (k.as_str(), to_cbor(v)))
            .collect();
        if !rest.is_empty() {
            params.push(("hf".into(), Value::map(rest)));
        }
    }
    (family, params)
}

