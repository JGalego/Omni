    #[test]
    fn the_imported_tokenizer_reads_back_and_encodes() {
        let out = import(&files(), &ImportOpts::default()).expect("imports");
        let packed = crate::container::pack(
            &out.objects,
            &out.root,
            &crate::container::PackOptions::default(),
        )
        .expect("packs");
        let c = crate::container::Container::open(packed).expect("opens");
        let store = crate::store::Borrowed(&c);
        let ctx = crate::expr::Ctx::new(&store);
        let manifest = c.root().expect("root");
        let tr = crate::expr::parse_ref_value(
            manifest
                .get("assets")
                .and_then(|a| a.get("tokenizer"))
                .expect("a tokenizer asset"),
        )
        .expect("ref");
        let tok = crate::tokenizer::Tokenizer::load(&ctx, &tr).expect("loads");
        assert_eq!(tok.vocab_size(), 9);
        assert_eq!(tok.merges.len(), 3);
        // The two normalizers this build does implement, in order.
        assert_eq!(tok.normalizers.len(), 2);
        assert!(tok.unsupported().is_empty(), "{:?}", tok.unsupported());
    }

